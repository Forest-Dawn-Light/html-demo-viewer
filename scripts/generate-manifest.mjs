/**
 * generate-manifest.mjs
 *
 * Scans demos/**\/*.html (recursively), reads optional .meta.json sidecar files,
 * and writes src/viewer/generated-pages.js for the viewer to consume.
 *
 * Usage:  node scripts/generate-manifest.mjs
 */

import { readdirSync, statSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'fs';
import { join, relative, extname, basename, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const DEMOS_DIR = join(ROOT, 'demos');
const OUTPUT_FILE = join(ROOT, 'src', 'viewer', 'generated-pages.js');

/** Recursively collect .html files under a directory */
function scanHtmlFiles(dir, results = []) {
  if (!existsSync(dir)) return results;
  for (const entry of readdirSync(dir)) {
    const fullPath = join(dir, entry);
    if (statSync(fullPath).isDirectory()) {
      scanHtmlFiles(fullPath, results);
    } else if (extname(entry) === '.html') {
      results.push(fullPath);
    }
  }
  return results;
}

/** Load optional sidecar .meta.json next to an HTML file */
function loadMeta(htmlPath) {
  const metaPath = htmlPath.replace(/\.html$/, '.meta.json');
  if (existsSync(metaPath)) {
    try {
      return JSON.parse(readFileSync(metaPath, 'utf-8'));
    } catch (e) {
      console.warn(`[generate-manifest] Failed to parse ${metaPath}: ${e.message}`);
    }
  }
  return {};
}

/** Turn a relative path into a slug-style id */
function pathToId(relativePath) {
  return relativePath
    .replace(/\.html$/, '')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

/** Derive a human-readable label from a file name */
function fileToLabel(htmlPath) {
  return basename(htmlPath, '.html')
    .replace(/[-_]/g, ' ')
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

/** Derive the group id from the first path segment under demos/ */
function inferGroup(relativePath) {
  const parts = relativePath.split('/');
  return parts.length > 1 ? parts[0] : 'default';
}

/** Turn a group id into a display label */
function groupToLabel(groupId) {
  return groupId
    .replace(/[-_]/g, ' ')
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

// ── Scan ────────────────────────────────────────────────────────────────────

const htmlFiles = scanHtmlFiles(DEMOS_DIR);
const pages = [];

for (const absPath of htmlFiles) {
  const relPath = relative(DEMOS_DIR, absPath).replace(/\\/g, '/');
  const meta = loadMeta(absPath);

  if (meta.hidden === true) continue;

  pages.push({
    id: meta.id || pathToId(relPath),
    path: `demos/${relPath}`,
    label: meta.label || fileToLabel(absPath),
    group: meta.group || inferGroup(relPath),
    order: typeof meta.order === 'number' ? meta.order : 999,
    tags: Array.isArray(meta.tags) ? meta.tags : [],
    description: meta.description || '',
    hidden: false,
    entry: meta.entry === true,
    thumbnail: meta.thumbnail || null,
  });
}

// Sort: group → order → label
pages.sort((a, b) => {
  if (a.group !== b.group) return a.group.localeCompare(b.group);
  if (a.order !== b.order) return a.order - b.order;
  return a.label.localeCompare(b.label);
});

// ── Groups ───────────────────────────────────────────────────────────────────

const groupMap = new Map();
for (const page of pages) {
  if (!groupMap.has(page.group)) {
    groupMap.set(page.group, {
      id: page.group,
      label: groupToLabel(page.group),
    });
  }
}

const groups = [...groupMap.values()].sort((a, b) => a.label.localeCompare(b.label));

// ── Page map ──────────────────────────────────────────────────────────────────

const pageMap = Object.fromEntries(pages.map((p) => [p.path, p]));

// ── Write output ──────────────────────────────────────────────────────────────

const output = `\
// Auto-generated by scripts/generate-manifest.mjs
// DO NOT edit manually — run \`npm run generate:manifest\` to update.

export const prototypeGroups = ${JSON.stringify(groups, null, 2)};

export const prototypePages = ${JSON.stringify(pages, null, 2)};

export const prototypePageMap = ${JSON.stringify(pageMap, null, 2)};
`;

mkdirSync(dirname(OUTPUT_FILE), { recursive: true });
writeFileSync(OUTPUT_FILE, output, 'utf-8');

console.log(
  `[generate-manifest] ${pages.length} page(s) in ${groups.length} group(s) → ${relative(ROOT, OUTPUT_FILE)}`,
);
